"""Bounded GET-only GitHub transport; credentials never enter observations or errors."""
import json
import os
import re
import urllib.error
import urllib.request

ORIGIN = "https://api.github.com"
MAX_BYTES = 2 * 1024 * 1024
# The only path with "...": compare of a base ref (no "..") with an exact head SHA (github_pr_base_reader).
COMPARE = re.compile(r"/repos/[A-Za-z0-9-]+/(?:[A-Za-z0-9_-]|\.(?!\.))+/compare/(?:[A-Za-z0-9_/-]|\.(?!\.))+"
                     r"\.\.\.[0-9a-f]{40}")


class GitHubReadError(ValueError):
    def __init__(self, message="GitHub observation is unavailable or incomplete.", *, status=None):
        super().__init__(message)
        self.status = status


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


class GitHubReviewTransport:
    def __init__(self, *, token=None, opener=None):
        self._token = token if token is not None else next(
            (os.environ[key] for key in ("OPORA_GITHUB_TOKEN", "GH_TOKEN", "GITHUB_TOKEN")
             if os.environ.get(key)), "")
        self._opener = opener or urllib.request.build_opener(
            urllib.request.ProxyHandler({}), _NoRedirect())

    def __call__(self, path, *, timeout):
        # Paths are generated by the reader. Defend the boundary also when called directly.
        if (not isinstance(path, str) or "//" in path or timeout <= 0 or not COMPARE.fullmatch(path)
                and (not re.fullmatch(r"/repos/[A-Za-z0-9_./?=&-]+", path) or ".." in path)):
            raise GitHubReadError("Invalid GitHub read request.")
        headers = {"Accept": "application/vnd.github+json", "User-Agent": "OporaHub",
                   "X-GitHub-Api-Version": "2022-11-28"}
        if self._token:
            headers["Authorization"] = "Bearer " + self._token
        request = urllib.request.Request(ORIGIN + path, headers=headers, method="GET")
        try:
            with self._opener.open(request, timeout=min(timeout, 10)) as response:
                if response.status != 200:
                    raise GitHubReadError(status=response.status)
                raw = response.read(MAX_BYTES + 1)
                if len(raw) > MAX_BYTES:
                    raise GitHubReadError("GitHub response exceeds the observation limit.")
                data = json.loads(raw)
                return data, {key.lower(): value for key, value in response.headers.items()}
        except urllib.error.HTTPError as error:
            raise GitHubReadError(status=error.code) from None
        except (OSError, ValueError) as error:
            if isinstance(error, GitHubReadError):
                raise
            raise GitHubReadError() from None
